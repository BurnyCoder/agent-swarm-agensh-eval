#!/usr/bin/env python3
"""Regenerate every number in the run report from the copied run artifacts.

Global context: each Agensh run leaves JSON records in out/projects/<name>/
(run_state, delivery, acceptance, main-health, prepare) and a per-request usage
ledger written by the egress proxy (.claude-team-data/<profile>/usage/usage.jsonl).
`runs/fetch_artifacts.sh` copies those (no secrets) plus the delivered branch's
first-parent git log into runs/<name>/. This script reads them and writes
reports/stats.json and reports/stats.md, so the report never carries hand-typed numbers.

Cost: Claude Haiku 5.5 prices (claude-api skill pricing notes): $0.10 / $0.50 per MTok
input / output for prompts up to 100K tokens ($0.50 / $2.50 above), cache reads 0.1x input,
5-minute cache writes 1.25x, 1-hour cache writes 2x. The proxy ledger does not record the
cache TTL, so cost is reported twice: all writes at 5 minutes ("low") and at 1 hour ("high").

Usage: python3 reports/collect_stats.py [runs_dir]
"""

import collections
import datetime
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CARDS = {False: (0.10, 0.01, 0.125, 0.20, 0.50), True: (0.50, 0.05, 0.625, 1.00, 2.50)}  # USD per MTok
FIELDS = ('input_tokens', 'cached_input_tokens', 'cache_creation_input_tokens', 'output_tokens')


def cost(u, hour_writes):
    fresh, read, write, out = (u.get(k, 0) or 0 for k in FIELDS)
    card = CARDS[fresh + read + write > 100_000]
    return (fresh * card[0] + read * card[1] + write * card[3 if hour_writes else 2] + out * card[4]) / 1e6


def stamp(text):
    return datetime.datetime.fromisoformat(text.replace('Z', '+00:00'))


def project_stats(run):
    load = lambda name: json.loads((run / name).read_text()) if (run / name).is_file() else {}
    state, delivery, acceptance, health = (load(n) for n in ('run_state.json', 'delivery.json',
                                                              'acceptance.json', 'main-health.json'))
    workers = collections.defaultdict(lambda: dict.fromkeys(FIELDS, 0) | {'requests': 0, 'low': 0.0, 'high': 0.0})
    models, statuses = collections.Counter(), collections.Counter()
    for line in (run / 'usage.jsonl').read_text().splitlines():
        try:
            row = json.loads(line)
        except ValueError:
            continue
        u, w = row.get('usage') or {}, workers[row.get('agent') or 'project']
        statuses[row.get('status')] += 1
        models[row.get('model')] += 1
        w['requests'] += 1
        for k in FIELDS:
            w[k] += u.get(k, 0) or 0
        w['low'] += cost(u, False)
        w['high'] += cost(u, True)
    total = {k: sum(w[k] for w in workers.values()) for k in (*FIELDS, 'requests', 'low', 'high')}
    segments = [{'mode': s['mode'], 'started': s['started'], 'ended': s.get('ended'), 'reason': s.get('reason'),
                 'minutes': round((stamp(s['ended']) - stamp(s['started'])).total_seconds() / 60, 1) if s.get('ended') else None}
                for s in state.get('segments', [])]
    commits = [line.split('|', 3) for line in (run / 'git-log.txt').read_text().splitlines() if line]
    team = [c for c in commits if c[1].startswith('team-worker')]
    tests = None
    for result in acceptance.get('results', []):
        match = re.search(r'(\d+) passed', result.get('output_tail', ''))
        tests = int(match.group(1)) if match else tests
    return {
        'state': state.get('state'), 'segments': segments,
        'work_minutes': round(sum(s['minutes'] or 0 for s in segments), 1),
        'requests': total['requests'], 'http_statuses': dict(statuses), 'models': dict(models),
        'tokens': {k: total[k] for k in FIELDS},
        'cost_usd': {'low': round(total['low'], 3), 'high': round(total['high'], 3)},
        'workers': {name: {**{k: v for k, v in w.items() if k not in ('low', 'high')},
                           'cost_low': round(w['low'], 3), 'cost_high': round(w['high'], 3)}
                    for name, w in sorted(workers.items())},
        'merged_prs_on_main': len(team), 'merges_by_worker': dict(collections.Counter(c[1] for c in team)),
        'first_merge': min((c[2] for c in team), default=None), 'last_merge': max((c[2] for c in team), default=None),
        'delivered_commits': delivery.get('commits'), 'delivery_mode': delivery.get('mode'),
        'delivery_target': delivery.get('branch') or delivery.get('bundle'),
        'acceptance_passed': acceptance.get('all_passed'), 'acceptance_tests_passed': tests,
        'main_broken_events': len(health.get('history', [])),
    }


def markdown(stats):
    lines = ['# Run statistics', '', 'Generated by `python3 reports/collect_stats.py` from `runs/*/`.', '',
             '| | ' + ' | '.join(stats) + ' |', '|---|' + '---|' * len(stats)]
    rows = [('state', lambda s: s['state']),
            ('driver time incl. bring-up and delivery (min)', lambda s: s['work_minutes']),
            ('segments', lambda s: '; '.join(f"{x['mode']} {x['minutes']} min ({x['reason']})" for x in s['segments'])),
            ('model requests', lambda s: s['requests']),
            ('models', lambda s: ', '.join(f'{m}: {n}' for m, n in s['models'].items())),
            ('uncached input tokens', lambda s: f"{s['tokens']['input_tokens']:,}"),
            ('cache-read tokens', lambda s: f"{s['tokens']['cached_input_tokens']:,}"),
            ('cache-write tokens', lambda s: f"{s['tokens']['cache_creation_input_tokens']:,}"),
            ('output tokens', lambda s: f"{s['tokens']['output_tokens']:,}"),
            ('cost, USD (5-min / 1-h cache writes)', lambda s: f"{s['cost_usd']['low']:.2f} / {s['cost_usd']['high']:.2f}"),
            ('PRs merged into main', lambda s: s['merged_prs_on_main']),
            ('merges by worker', lambda s: ', '.join(f'{k[5:]}: {v}' for k, v in sorted(s['merges_by_worker'].items()))),
            ('first / last merge (UTC)', lambda s: f"{(s['first_merge'] or '')[11:16]} / {(s['last_merge'] or '')[11:16]}"),
            ('delivered commits', lambda s: s['delivered_commits']),
            ('delivery', lambda s: f"{s['delivery_mode']}: `{s['delivery_target'] if s['delivery_mode'] == 'branch' else Path(str(s['delivery_target'])).name}`"),
            ('acceptance on delivered head', lambda s: f"{'pass' if s['acceptance_passed'] else 'FAIL'} ({s['acceptance_tests_passed']} tests)"),
            ('main-broken events', lambda s: s['main_broken_events'])]
    lines += [f'| {label} | ' + ' | '.join(str(fn(s)) for s in stats.values()) + ' |' for label, fn in rows]
    total_low = sum(s['cost_usd']['low'] for s in stats.values())
    total_high = sum(s['cost_usd']['high'] for s in stats.values())
    lines += ['', f'Total team cost: ${total_low:.2f}–${total_high:.2f}.', '']
    for name, s in stats.items():
        lines += [f'## {name}: per worker', '', '`project` = the app\'s own model calls on the team route (e.g. `eval --generate`).', '',
                  '| worker | requests | output tokens | cost USD (1-h writes) |', '|---|---|---|---|']
        lines += [f"| {w} | {v['requests']} | {v['output_tokens']:,} | {v['cost_high']:.2f} |" for w, v in s['workers'].items()]
        lines.append('')
    return '\n'.join(lines)


def main():
    runs = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'runs'
    stats = {d.name: project_stats(d) for d in sorted(runs.iterdir()) if (d / 'usage.jsonl').is_file()}
    (ROOT / 'reports' / 'stats.json').write_text(json.dumps(stats, indent=2) + '\n')
    (ROOT / 'reports' / 'stats.md').write_text(markdown(stats))
    print(markdown(stats))


if __name__ == '__main__':
    main()
